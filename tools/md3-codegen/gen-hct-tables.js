const src = fs.readFileSync(SRC, 'utf8');

function slice(name) {
    const start = src.indexOf(`HctSolver.${name} = `);
    if (start < 0) throw new Error('未找到 ' + name);
    const open = src.indexOf('[', start);
    // 括号配对
    let depth = 0, i = open;
    for (; i < src.length; i++) {
        if (src[i] === '[') depth++;
        else if (src[i] === ']') { depth--; if (depth === 0) break; }
    }
    return src.slice(open, i + 1);
}
function nums(text) {
    return (text.match(/-?\d+\.?\d*(?:e-?\d+)?/gi) || []).map(Number);
}
function fmt(v) {
    const s = String(v);
    return s.includes('.') || s.includes('e') ? s : s + '.0';
}
function cs1(arr, indent) {
    const parts = arr.map(v => fmt(v));
    const lines = [];
    for (let i = 0; i < parts.length; i += 5) lines.push(indent + parts.slice(i, i + 5).join(', ') + ',');
    return lines.join('\n');
}
function cs2(m) {
    return m.map(row => '            new double[] { ' + row.map(fmt).join(', ') + ' },').join('\n');
}

const sdl = nums(slice('SCALED_DISCOUNT_FROM_LINRGB'));
const lfs = nums(slice('LINRGB_FROM_SCALED_DISCOUNT'));
const yfl = nums(slice('Y_FROM_LINRGB'));
const cp = nums(slice('CRITICAL_PLANES'));
const m2 = a => [a.slice(0, 3), a.slice(3, 6), a.slice(6, 9)];

